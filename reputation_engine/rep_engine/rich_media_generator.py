def _generate_note_asset(
    asset_type: str, biz: dict, sources: list[dict], business_id: int
) -> Optional[str]:
    """Generate a note-type asset. Tries the real NotebookLM note API only when NOTEBOOKLM_ENABLED
    (dormant by default); otherwise, and on any failure, uses the in-house LLM. Returns markdown."""
    if _tools.over_budget(business_id):
        raise _tools.BudgetExceededError(f"business {business_id} is over monthly budget")
    if _notebooklm_live():
        note_type = _NOTE_TYPE_MAP.get(asset_type, "briefing_doc")
        title = f"{biz.get('name', 'Business')} — {note_type.replace('_', ' ').title()}"
        raw = _nlm.synthesise_note(sources, title, note_type, _api_key())
        if raw:
            return raw
        log.warning("rich_media: NotebookLM returned no note for %s, falling back to LLM",
                    asset_type)
    return _fallback_llm(asset_type, biz, sources, business_id)

    # Post-process: wrap raw note into the target format.
    return _format_note(asset_type, raw, biz)


def _format_note(asset_type: str, raw: str, biz: dict) -> str:
    """Wrap a raw NotebookLM note into the target asset format."""
    name = biz.get("name", "the business")
    if asset_type == "slide_deck":
        return (
            f"# Slide Deck Brief — {name}\n\n"
            "**Instructions for deck designer:** Convert each section below into one slide. "
            "Add brand visuals, data charts from the monthly report, and the company logo.\n\n"
            + raw
        )
    if asset_type == "infographic":
        return (
            f"# Infographic Brief — {name}\n\n"
            "**Instructions for designer:** Convert the Q&A pairs below into an infographic. "
            "Use icons for each section, brand colors, and a clear headline at the top.\n\n"
            + raw
        )
    if asset_type == "explainer_video":
        return (
            f"# Explainer Video Script — {name}\n\n"
            "**Instructions for production:** Use the study-guide outline below as the "
            "script skeleton. Record a talking-head or animated explainer of 2-4 minutes. "
            "Pair with the video production briefs in the monthly report for full specs.\n\n"
            + raw
        )
    if asset_type == "research_brief":
        return (
            f"# Research Brief — {name}\n\n"
            "**For:** PR teams, journalists, content collaborators\n\n" + raw
        )
    return raw


def _fallback_llm(
    asset_type: str, biz: dict, sources: list[dict], business_id: int
) -> Optional[str]:
    """In-house LLM fallback when NotebookLM key is absent or generation fails."""
    template = _LLM_PROMPTS.get(asset_type)
    if not template:
        # For note-type assets, build a generic structured prompt.
        template = (
            "Using the context below, generate a {asset_type} for {{name}}. "
            "Format clearly in markdown. No fabricated facts, no performance promises."
        ).format(asset_type=asset_type.replace("_", " "))
    system = (
        "You are an expert reputation marketing strategist. Write structured, accurate "
        "content for reputation management. Never fabricate statistics, credentials, or "
        "performance data — use [INSERT: ...] placeholders for unknown facts. Apply "
        "financial-marketing compliance: no guaranteed returns, no 'risk-free', no '#1' "
        "or 'best' as stated fact. Output ONLY the asset content in markdown."
    )
    prompt_text = template.format(name=biz.get("name", "the business"))
    # Add source context. The client's own material (Business Profile, Requested Focus, BRAND RULES,
    # Client Source Material) leads the sources list, so keep the first 6 and allow a generous
    # per-source budget — the old 5x3000-char cap dropped ~90% of a large uploaded corpus.
    context = "\n\n---\n\n".join(
        f"## {s['title']}\n{s['text'][:6_000]}" for s in sources[:6]
    )
    user = f"{prompt_text}\n\n# Context\n\n{context}"
    try:
        if _tools.over_budget(business_id):
            raise _tools.BudgetExceededError(
                f"business {business_id} is over monthly budget")
        return _tools.llm_text(
            system, user,
            business_id=business_id,
            tier="mid",
            max_tokens=3_000,
            operation=f"rich_media_{asset_type}",
        )
    except _tools.BudgetExceededError:
        raise
    except Exception as e:
        log.warning("rich_media: LLM fallback for %s failed: %s", asset_type, e)
        return None


def _generate_llm_asset(
    asset_type: str, biz: dict, sources: list[dict], business_id: int
) -> Optional[str]:
    """Generate an LLM-structured asset using the in-house LLM path."""
    return _fallback_llm(asset_type, biz, sources, business_id)


# ---------------------------------------------------------------------------
# Persistence
# ---------------------------------------------------------------------------

def _persist(
    business_id: int,
    asset_type: str,
    title: str,
    *,
    body: Optional[str] = None,
    audio_url: Optional[str] = None,
    transcript: Optional[str] = None,
    duration_secs: Optional[int] = None,
    sources_used: list | None = None,
    compliance_pass: Optional[bool] = None,
    compliance_flags: list | None = None,
    generator: str = "llm",
) -> int:
    with db() as conn:
        row = conn.execute(
            """INSERT INTO rich_media_drafts
               (business_id, asset_type, title, body, audio_url, transcript,
                duration_secs, sources_used, compliance_pass, compliance_flags, generator, status)
               VALUES (%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,'pending_review') RETURNING id""",
            (business_id, asset_type, title,
             body, audio_url, transcript, duration_secs,
             json.dumps(sources_used or []),
             compliance_pass, json.dumps(compliance_flags or []), generator),
        ).fetchone()
        conn.commit()
    log.info("rich_media: saved draft %d (%s, generator=%s, compliance=%s)", row["id"],
             asset_type, generator, compliance_pass)
    return row["id"]


# ---------------------------------------------------------------------------
# Orchestrated generation
# ---------------------------------------------------------------------------

def generate(
    business_id: int,
    asset_types: Optional[list[str]] = None,
    topic: Optional[str] = None,
) -> list[int]:
    """Generate rich media drafts for a business.

    Args:
        business_id: DB id of the business to generate for.
        asset_types: List of asset_type strings to generate. Defaults to
                     DEFAULT_TYPES. Unknown types are silently skipped.
        topic: Optional user-requested focus (from the "Create content" box). When set, it's
               injected as a top-priority source so the generated piece is ABOUT what the user
               asked for, not just a generic synthesis of the whole corpus.

    Returns:
        List of draft ids created.
    """
    _ensure_table()

    # Pre-flight budget check.
    if _tools.over_budget(business_id):
        log.warning("rich_media: business %d over budget — skipping all", business_id)
        return []

    # Load business profile.
    with db() as conn:
        biz_row = conn.execute(
            "SELECT * FROM businesses WHERE id=%s", (business_id,)
        ).fetchone()
        if not biz_row:
            raise SystemExit(f"No business id {business_id}")
    biz = dict(biz_row)

    # Assemble corpus sources once; reuse across all generation calls.
    sources = _build_sources(business_id, biz)
    # A user-requested focus (from "Create content") steers generation to what they asked for.
    # Placed right after the Business Profile so it's high-priority context, not buried.
    topic = (topic or "").strip()
    if topic:
        sources.insert(1, {"title": "Requested Focus (make the piece about THIS)", "text": topic})
    source_titles = [s["title"] for s in sources]

    types_to_run = asset_types or DEFAULT_TYPES
    created: list[int] = []

    for asset_type in types_to_run:
        if asset_type not in RICH_TYPES:
            log.warning("rich_media: unknown asset_type %r — skipping", asset_type)
            continue

        method, description = RICH_TYPES[asset_type]
        log.info("rich_media: generating %s (%s)", asset_type, description)
        title = (f"{biz.get('name', 'Business')} — {topic[:80]}" if topic
                 else f"{biz.get('name', 'Business')} — {asset_type.replace('_', ' ').title()}")

        try:
            if method == "notebooklm_audio":
                result = _generate_audio(asset_type, biz, sources, business_id)
                if not result:
                    log.info("rich_media: %s skipped (no audio result)", asset_type)
                    continue
                transcript = result.get("transcript") or ""
                comp_pass, comp_flags = _compliance_check(transcript)
                draft_id = _persist(
                    business_id, asset_type, title,
                    body=transcript,
                    audio_url=result.get("audio_url"),
                    transcript=transcript,
                    duration_secs=result.get("duration_seconds"),
                    sources_used=source_titles,
                    compliance_pass=comp_pass,
                    compliance_flags=comp_flags,
                    generator=result.get("generator") or "llm",
                )
                created.append(draft_id)

            elif method == "notebooklm_note":
                body = _generate_note_asset(asset_type, biz, sources, business_id)
                if not body:
                    log.info("rich_media: %s produced no content — skipping", asset_type)
                    continue
                comp_pass, comp_flags = _compliance_check(body)
                draft_id = _persist(
                    business_id, asset_type, title,
                    body=body,
                    sources_used=source_titles,
                    compliance_pass=comp_pass,
                    compliance_flags=comp_flags,
                    generator="notebooklm" if _notebooklm_live() else "llm",
                )
                created.append(draft_id)

            elif method == "llm_structured":
                body = _generate_llm_asset(asset_type, biz, sources, business_id)
                if not body:
                    log.info("rich_media: %s produced no content — skipping", asset_type)
                    continue
                comp_pass, comp_flags = _compliance_check(body)
                draft_id = _persist(
                    business_id, asset_type, title,
                    body=body,
                    sources_used=source_titles,
                    compliance_pass=comp_pass,
                    compliance_flags=comp_flags,
                    generator="llm",
                )
                created.append(draft_id)

            # NOTE: no flat per-asset cost record here. Every path now routes LLM generation through
            # _fallback_llm -> agent_tools.llm_text, which token-meters the spend to the ledger. A
            # flat record here would DOUBLE-count it (the old code did, for note-fallback pieces).
            # When a real NotebookLM/AutoContent provider is wired, its adapter records its own cost.

        except _tools.BudgetExceededError:
            log.warning("rich_media: budget exceeded mid-run; stopping at %s", asset_type)
            break
        except Exception as e:  # noqa: BLE001
            log.warning("rich_media: %s failed: %s — continuing", asset_type, e)
            continue

    # A run that was asked for specific types but produced NOTHING is a real failure (LLM +
    # NotebookLM both unavailable, or every type errored) -- surface it loudly rather than reading
    # as a silent success. (The single-WO custom-content path also fails via content_generator's
    # 0-draft guard; this covers the direct/bulk callers.)
    if not created and types_to_run:
        log.warning("rich_media: produced 0 of %d requested type(s) for business %d -- generation "
                    "failed (check the NotebookLM/orchestrator LLM availability).",
                    len(types_to_run), business_id)
    else:
        log.info("rich_media: created %d draft(s) for business %d", len(created), business_id)
    return created


