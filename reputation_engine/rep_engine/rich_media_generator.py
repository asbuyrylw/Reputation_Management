def configured() -> bool:
    """Whether the full NotebookLM path (incl. podcast AUDIO) is available. Text rich media always
    works via the in-house LLM fallback; only audio needs a key."""
    return bool(_api_key())


def _iso(d: dict, *keys) -> dict:
    for k in keys:
        if d.get(k) is not None and hasattr(d[k], "isoformat"):
            d[k] = d[k].isoformat()
    return d


def api_list(business_id: int, asset_type: Optional[str] = None, status: Optional[str] = None,
             limit: int = 100) -> list[dict]:
    """List rich-media drafts (podcast/deck/infographic/explainer/…) for the media gallery.
    Returns lightweight rows (no full body) + flags for what viewer to use. Dormant-safe."""
    _ensure_table()
    q = ("SELECT id, asset_type, title, audio_url, duration_secs, status, compliance_pass, "
         "compliance_flags, geo_score, quality_notes, created_at, updated_at, generator, notebook_url, "
         "(body IS NOT NULL AND length(body) > 0) AS has_body, "
         "(transcript IS NOT NULL AND length(transcript) > 0) AS has_transcript "
         "FROM rich_media_drafts WHERE business_id=%s")
    args: list = [business_id]
    if asset_type:
        q += " AND asset_type=%s"; args.append(asset_type)
    if status:
        q += " AND status=%s"; args.append(status)
    q += " ORDER BY id DESC LIMIT %s"; args.append(limit)
    with db() as conn:
        rows = conn.execute(q, tuple(args)).fetchall()
    return [_iso(dict(r), "created_at", "updated_at") for r in rows]


def api_get(business_id: int, draft_id: int) -> Optional[dict]:
    """Full rich-media draft incl. body + transcript, for the viewer modal."""
    _ensure_table()
    with db() as conn:
        r = conn.execute("SELECT * FROM rich_media_drafts WHERE id=%s AND business_id=%s",
                         (draft_id, business_id)).fetchone()
    return _iso(dict(r), "created_at", "updated_at", "reviewed_at") if r else None


def set_status(business_id: int, draft_id: int, status: str, reviewer: Optional[str] = None) -> bool:
    """Approve/reject a rich-media draft (human gate). Returns True if a row was updated."""
    _ensure_table()
    with db() as conn:
        r = conn.execute(
            "UPDATE rich_media_drafts SET status=%s, reviewer=%s, reviewed_at=now(), updated_at=now() "
            "WHERE id=%s AND business_id=%s RETURNING id", (status, reviewer, draft_id, business_id)).fetchone()
        conn.commit()
    return bool(r)


def _grade_body(asset_type: str, body: Optional[str], business_name: str = "", geo: str = "") -> tuple:
    """Grade a (possibly edited) rich-media body -> (geo_grade, quality_notes, status). Mirrors the
    grading in _persist so an EDIT re-scores exactly like generation does: video scripts get
    video_score; other text-like types get geo_score; audio (podcast/report_audio) is unscored; a body
    that ends mid-sentence is flagged truncated -> needs_fix."""
    quality_notes, geo_grade, status = None, None, "pending_review"
    try:
        from . import content_quality as _cq
        if body and asset_type in ("explainer_video", "video_script"):
            vg = _cq.video_score(body, target_query=f"{business_name} {geo}".strip(),
                                 business_name=business_name, geo=geo, asset_type=asset_type)
            quality_notes, geo_grade = vg, vg.get("score")
        elif body and (asset_type not in ("podcast", "report_audio") or len((body or "").split()) >= 120):
        # ALSO score substantial audio TRANSCRIPTS (an LLM two-host podcast script, 600-900 words) with
        # the same GEO/citability grade -- the transcript IS the citable content. The short NotebookLM
        # "open in Studio to listen" link message (~50 words) is naturally excluded by the word gate.
            _geo = _cq.geo_score(body, target_query=f"{business_name} {geo}".strip(),
                                 content_type=asset_type, asset_type=asset_type,
                                 business_name=business_name, geo=geo)
            quality_notes = {"geo": _geo}
            geo_grade = _geo.get("score")
    except Exception as e:  # noqa: BLE001 -- grading must never block an edit
        log.debug("rich_media: re-grade skipped: %s", e)
    if body and len(body.split()) >= 120:
        _tail = body.rstrip()
        if _tail and _tail[-1] not in ".!?\"”')]:*_`>":
            quality_notes = dict(quality_notes or {})
            quality_notes["truncated"] = {"ends_with": _tail[-80:],
                                          "reason": "body ends mid-sentence (likely token-cap truncation)"}
            status = "needs_fix"
    return geo_grade, quality_notes, status


def update_draft(business_id: int, draft_id: int, *, body: Optional[str] = None,
                 transcript: Optional[str] = None, reviewer: Optional[str] = None) -> Optional[dict]:
    """Edit a rich-media draft's body/transcript and RE-GRADE it (geo_score + truncation + compliance),
    so a human fix updates the scores + status the same way generation does. Returns the updated draft
    (full row) or None if not found. Body is placeholder-stripped + license-scrubbed like a new draft."""
    _ensure_table()
    with db() as conn:
        cur = conn.execute("SELECT asset_type, body, transcript FROM rich_media_drafts "
                           "WHERE id=%s AND business_id=%s", (draft_id, business_id)).fetchone()
        b = conn.execute("SELECT name, geo, contested_terms FROM businesses WHERE id=%s",
                         (business_id,)).fetchone()
    if not cur:
        return None
    asset_type = cur["asset_type"]
    new_body = body if body is not None else cur["body"]
    new_transcript = transcript if transcript is not None else cur["transcript"]
    _profile = {}
    if new_body:
        try:
            from . import content_generator as _cg
            _profile = _bp.for_business(business_id)
            new_body = _cg._scrub_license_phrasing(_cg._strip_placeholders(new_body), _profile)
            # Same crowd-out pass as generation (headings + lead) so an edit can't reintroduce
            # contested framing into the extractable locations.
            new_body = _cg.neutralize_contested(new_body, (b.get("contested_terms") if b else "") or "")
        except Exception as e:  # noqa: BLE001 -- cleanup must never block the edit
            log.debug("rich_media: edit cleanup skipped: %s", e)
    bn = (b["name"] if b else "") or ""
    geo = (b.get("geo") if b else "") or ""
    geo_grade, quality_notes, status = _grade_body(asset_type, new_body, bn, geo)
    comp_pass, comp_flags = None, []
    try:
        comp_pass, comp_flags = _compliance_check(
            new_body or "", regulated_financial=bool((_profile or {}).get("regulated_financial")))
    except Exception as e:  # noqa: BLE001
        log.debug("rich_media: edit compliance skipped: %s", e)
    if comp_pass is False and status == "pending_review":
        status = "needs_fix"   # a compliance failure holds the edited draft out of the ready queue too
    with db() as conn:
        r = conn.execute(
            "UPDATE rich_media_drafts SET body=%s, transcript=%s, geo_score=%s, quality_notes=%s, "
            "compliance_pass=%s, compliance_flags=%s, status=%s, reviewer=%s, updated_at=now() "
            "WHERE id=%s AND business_id=%s RETURNING id",
            (new_body, new_transcript, geo_grade, json.dumps(quality_notes) if quality_notes else None,
             comp_pass, json.dumps(comp_flags or []), status, reviewer, draft_id, business_id)).fetchone()
        conn.commit()
    return api_get(business_id, draft_id) if r else None


def delete_draft(business_id: int, draft_id: int) -> bool:
    """Permanently delete a rich-media draft (explicit owner action). If the draft has a rendered
    video (quality_notes.rendered_video.visual_id), the linked visual_asset is deleted too so a
    delete doesn't orphan the rendered MP4. Tenancy-scoped. Returns True if a row was removed."""
    _ensure_table()
    with db() as conn:
        r = conn.execute("SELECT quality_notes FROM rich_media_drafts WHERE id=%s AND business_id=%s",
                         (draft_id, business_id)).fetchone()
        if not r:
            return False
        qn = r.get("quality_notes")
        if isinstance(qn, str):
            try:
                qn = json.loads(qn)
            except (ValueError, TypeError):
                qn = {}
        vid = (qn.get("rendered_video") or {}).get("visual_id") if isinstance(qn, dict) else None
        conn.execute("DELETE FROM rich_media_drafts WHERE id=%s AND business_id=%s",
                     (draft_id, business_id))
        conn.commit()
    if vid:
        try:
            from . import visual_content as _vc
        except ImportError:  # pragma: no cover
            import visual_content as _vc  # type: ignore
        try:
            _vc.delete_visual(int(vid), business_id)
        except Exception as e:  # noqa: BLE001 - the draft is gone; a dangling visual is non-fatal
            log.warning("delete_draft: could not remove linked visual %s: %s", vid, e)
    return True


def _record_rendered_video(business_id: int, draft_id: int, d: dict, res: dict, provider: str) -> None:
    """Store the rendered-video reference on the draft (so the review UI links the draft to its video)."""
    with db() as conn:
        qn = d.get("quality_notes") if isinstance(d.get("quality_notes"), dict) else {}
        qn = dict(qn or {})
        qn["rendered_video"] = {"visual_id": res.get("visual_id"), "video_url": res.get("video_url"),
                                "duration": res.get("duration"), "provider": provider}
        conn.execute("UPDATE rich_media_drafts SET quality_notes=%s, updated_at=now() "
                     "WHERE id=%s AND business_id=%s", (json.dumps(qn), draft_id, business_id))
        conn.commit()


def _render_veo(business_id: int, draft_id: int, d: dict, script: str) -> dict:
    """Alternative renderer: Google Veo 3.1 (via the existing Gemini/Veo path in visual_content). Veo
    GENERATES cinematic video + native audio from a prompt, so it is best for a short cinematic
    clip / B-roll / intro — NOT verbatim narration (the compliance-safe verbatim path is HeyGen). Veo
    caps at ~8s per clip; a full-length Veo explainer would need clip-chaining (a follow-up). Dormant-
    safe: {skipped} without VIDEO_PROVIDER=veo + a key."""
    try:
        from . import visual_content as _vc, heygen_video as _hg
    except ImportError:  # pragma: no cover
        import visual_content as _vc  # type: ignore
        import heygen_video as _hg  # type: ignore
    if not _vc.video_configured():
        return {"skipped": True,
                "reason": "Veo not configured — set VIDEO_PROVIDER=veo + VIDEO_API_KEY (or GEMINI_API_KEY)"}
    narration = _hg.narration_from_script(script)[:600]
    prompt = ("A short, professional explainer clip for a trustworthy professional team: a warm, "
              "credible presenter in a bright modern office, clean corporate look, no on-screen text. "
              f"Spoken narration (say verbatim): \"{narration}\"")
    res = _vc.generate_video(business_id, prompt, draft_id=draft_id, work_order_id=d.get("work_order_id"))
    if res.get("ok"):
        _record_rendered_video(business_id, draft_id, d, {"visual_id": res.get("visual_id"),
                               "video_url": None, "duration": None}, "veo")
        log.info("rendered Veo clip for rich-media draft %s (visual %s)", draft_id, res.get("visual_id"))
    return res


def render_video_for_draft(business_id: int, draft_id: int, reviewer: Optional[str] = None,
                           provider: Optional[str] = None, *, avatar_id: Optional[str] = None,
                           voice_id: Optional[str] = None, aspect: Optional[str] = None,
                           background: Optional[str] = None) -> dict:
    """Render a REAL MP4 for an explainer_video/video_script draft. Two selectable renderers:
      - HEYGEN (default) — an avatar speaks the already-vetted script VERBATIM (deterministic +
        brand-safe; no generated/hallucinated speech). Best for the full narrated explainer.
      - VEO 3.1 — Google's generative video + native audio (via the Gemini key). Best for a short
        cinematic clip / B-roll; its narration is GENERATED (not verbatim), so it carries the usual
        generative-content compliance caveat for regulated finance.
    Provider comes from the `provider` arg, else VIDEO_RENDER_PROVIDER, else 'heygen'. `avatar_id` /
    `voice_id` / `aspect` override the defaults so an owner 'send back with changes' can re-render the
    same (edited) script with a different presenter / voice / orientation. Stores the video as a `video`
    visual_asset (plays in the Media gallery + uploadable to YouTube) and records it on the draft.
    Explicit owner action (cost per render). Dormant-safe. Never raises."""
    d = api_get(business_id, draft_id)
    if not d:
        return {"ok": False, "error": "draft not found"}
    if d.get("asset_type") not in ("explainer_video", "video_script"):
        return {"ok": False, "error": f"draft {draft_id} is a {d.get('asset_type')}, not a video script"}
    script = (d.get("body") or d.get("transcript") or "").strip()
    if not script:
        return {"ok": False, "error": "draft has no script to render"}
    which = (provider or os.getenv("VIDEO_RENDER_PROVIDER", "heygen")).strip().lower()
    if which in ("veo", "gemini"):
        return _render_veo(business_id, draft_id, d, script)
    try:
        from . import heygen_video as _hg
    except ImportError:  # pragma: no cover
        import heygen_video as _hg  # type: ignore
    if not _hg.configured():
        return {"skipped": True,
                "reason": "HeyGen not configured — set HEYGEN_API_KEY on the worker (or choose the Veo renderer)"}
    title = d.get("title") or "Explainer video"
    if which in ("heygen_agent", "agent", "video_agent", "produced"):
        # v3 Video Agent (produced: B-roll + motion graphics). Non-verbatim -> load the business
        # name/geo for the structured, compliance-constrained prompt; human-reviewed before publish.
        # ASYNC: the render takes ~20-45 min, so CREATE the session + return immediately (never block
        # the sequential worker); the hourly poll_video_renders sweep downloads + stores it when ready.
        with db() as conn:
            b = conn.execute("SELECT name, geo FROM businesses WHERE id=%s", (business_id,)).fetchone()
        cb_base = _hg.callback_base()
        started = _hg.start_agent_session(business_id, script, title=title,
                                          business_name=(b or {}).get("name") or "",
                                          geo=(b or {}).get("geo") or "",
                                          callback_url=(f"{cb_base}/webhooks/heygen" if cb_base else None),
                                          callback_id=f"{business_id}:{draft_id}")
        if not started.get("ok"):
            return started
        with db() as conn:
            qn = d.get("quality_notes") if isinstance(d.get("quality_notes"), dict) else {}
            qn = dict(qn or {})
            qn["rendered_video"] = {"provider": "heygen_agent", "status": "rendering",
                                    "session_id": started["session_id"], "video_id": started.get("video_id"),
                                    "prompt": (started.get("prompt") or "")[:500],
                                    "work_order_id": d.get("work_order_id")}
            conn.execute("UPDATE rich_media_drafts SET quality_notes=%s, updated_at=now() "
                         "WHERE id=%s AND business_id=%s", (json.dumps(qn), draft_id, business_id))
            conn.commit()
        # Ensure the completion sweep runs (hourly fallback; downloads the MP4 when the Agent finishes).
        try:
            from . import scheduler as _sch
            _sch.upsert_schedule(business_id, "poll_video_renders", 1)
        except Exception as e:  # noqa: BLE001
            log.debug("could not schedule poll_video_renders: %s", e)
        log.info("started HeyGen Video Agent for draft %s (session %s)", draft_id, started["session_id"])
        return {"ok": True, "pending": True, "session_id": started["session_id"],
                "message": "Produced video started (~20-45 min) — it will appear in Media when ready."}
    res = _hg.render(business_id, script, title=title, work_order_id=d.get("work_order_id"),
                     draft_id=draft_id, avatar_id=avatar_id, voice_id=voice_id,
                     aspect=(aspect or "16:9"), background=background)
    if res.get("ok"):
        _record_rendered_video(business_id, draft_id, d, res, "heygen")
        log.info("rendered HeyGen video for rich-media draft %s (visual %s)", draft_id, res.get("visual_id"))
    return res


def ingest_notebook_audio(business_id: int, draft_id: int, audio_bytes: bytes,
                          mime: str = "audio/mpeg", *, source_artifact_id: Optional[str] = None,
                          filename: str = "podcast.mp3") -> dict:
    """Store a NotebookLM audio file (fetched by the browser automation) durably and attach it to the
    podcast draft so the Media modal plays it IN-APP instead of behind an "open & download" link.
    Idempotent on source_artifact_id. Returns {ok, visual_id, audio_url} or {ok:False, error}."""
    if not audio_bytes:
        return {"ok": False, "error": "no audio bytes"}
    _ensure_table()
    with db() as conn:
        r = conn.execute("SELECT quality_notes, audio_url FROM rich_media_drafts WHERE id=%s AND business_id=%s",
                         (draft_id, business_id)).fetchone()
    if not r:
        return {"ok": False, "error": "draft not found"}
    qn = r.get("quality_notes") if isinstance(r.get("quality_notes"), dict) else {}
    ra = (qn or {}).get("rendered_audio") or {}
    if source_artifact_id and ra.get("artifact_id") == source_artifact_id and r.get("audio_url"):
        return {"ok": True, "visual_id": ra.get("visual_id"), "audio_url": r.get("audio_url"), "idempotent": True}
    try:
        from . import visual_content as _vc
        skey, purl, path, fbytes = _vc._store_bytes(business_id, audio_bytes, filename, mime)
        vid = _vc._persist(business_id, kind="audio", provider="notebooklm", model=None,
                           prompt="NotebookLM audio overview", file_path=path, url=None,
                           compliance_note=None, draft_id=draft_id, file_bytes=fbytes, mime=mime,
                           storage_key=skey, public_url=purl)
    except Exception as e:  # noqa: BLE001
        return {"ok": False, "error": f"store failed: {e}"}
    audio_url = purl   # object-store public URL (requires object storage configured, which prod has)
    # Merge rendered_audio SERVER-SIDE (jsonb ||) so a concurrent grade/edit write to quality_notes
    # isn't clobbered by writing back the stale in-memory object read before the (slow) upload above.
    _delta = json.dumps({"rendered_audio": {"visual_id": vid, "url": audio_url,
                                            "artifact_id": source_artifact_id, "provider": "notebooklm"}})
    with db() as conn:
        conn.execute("UPDATE rich_media_drafts SET audio_url=COALESCE(%s, audio_url), generator='notebooklm', "
                     "quality_notes=COALESCE(quality_notes,'{}'::jsonb) || %s::jsonb, updated_at=now() "
                     "WHERE id=%s AND business_id=%s",
                     (audio_url, _delta, draft_id, business_id))
        conn.commit()
    if not audio_url:
        log.warning("ingest_notebook_audio: stored audio visual %s but no public_url (object storage not "
                    "configured) -- draft has the file but the in-app player URL is empty", vid)
    return {"ok": bool(audio_url), "visual_id": vid, "audio_url": audio_url,
            "error": None if audio_url else "object storage not configured (no public URL for playback)"}


def _download_one_audio(business_id: int, draft_id: int, _nle, _nbb) -> dict:
    """Fetch + ingest the audio for ONE podcast/report_audio draft. May raise; callers wrap it."""
    d = api_get(business_id, draft_id)
    if not d:
        return {"ok": False, "error": "draft not found"}
    if d.get("asset_type") not in ("podcast", "report_audio"):
        return {"ok": False, "error": f"draft is a {d.get('asset_type')}, not an audio type"}
    style = "briefing" if d.get("asset_type") == "report_audio" else "podcast"
    nb, _url, _seen = _nle._load_notebook(business_id, style)
    if not nb:
        return {"ok": False, "error": "no persistent notebook for this business yet (generate a podcast first)"}
    res = _nbb.fetch_latest_audio(nb)
    if res.get("skipped") or not res.get("ok"):
        return res
    return ingest_notebook_audio(business_id, draft_id, res.get("file_bytes") or b"",
                                 res.get("mime") or "audio/mpeg",
                                 source_artifact_id=res.get("source_artifact_id"),
                                 filename=res.get("filename") or "podcast.mp3")


def notebooklm_download_audio(business_id: int, draft_id: Optional[int] = None) -> dict:
    """Fetch the just-created NotebookLM audio and ingest it so it plays in Media in-app. draft_id set ->
    that one draft (fail-loud for the job); draft_id None -> SWEEP every pending audio draft (podcast/
    report_audio, generator='notebooklm', no rendered_audio yet) and self-clear the hourly sweep once the
    queue is empty (mirrors poll_video_renders). Dormant-safe: returns {skipped} until the browser session
    is configured. NEVER raises."""
    try:
        from . import notebooklm_enterprise as _nle, notebooklm_browser as _nbb
    except ImportError:  # pragma: no cover
        import notebooklm_enterprise as _nle  # type: ignore
        import notebooklm_browser as _nbb  # type: ignore
    if not _nbb.configured():
        return {"skipped": True, "reason": "notebooklm browser automation not configured"}
    _ensure_table()
    if draft_id:
        try:
            return _download_one_audio(business_id, draft_id, _nle, _nbb)
        except Exception as e:  # noqa: BLE001 -- honor the never-raises contract
            return {"ok": False, "error": f"audio download failed: {e}"}
    # sweep mode
    try:
        with db() as conn:
            rows = conn.execute(
                "SELECT id FROM rich_media_drafts WHERE business_id=%s "
                "AND asset_type IN ('podcast','report_audio') AND generator='notebooklm' "
                "AND (quality_notes->'rendered_audio') IS NULL AND coalesce(status,'') <> 'rejected' "
                "ORDER BY id DESC LIMIT 10", (business_id,)).fetchall()
        targets = [r["id"] for r in rows]
    except Exception as e:  # noqa: BLE001
        return {"ok": False, "error": f"sweep query failed: {e}"}
    done = failed = 0
    for did in targets:
        try:
            r = _download_one_audio(business_id, did, _nle, _nbb)
        except Exception as e:  # noqa: BLE001
            r = {"ok": False, "error": str(e)[:200]}
        if r.get("ok"):
            done += 1
        elif not r.get("skipped"):
            failed += 1
    try:   # self-clear the hourly sweep once nothing is pending
        with db() as conn:
            still = conn.execute(
                "SELECT count(*) AS n FROM rich_media_drafts WHERE business_id=%s "
                "AND asset_type IN ('podcast','report_audio') AND generator='notebooklm' "
                "AND (quality_notes->'rendered_audio') IS NULL AND coalesce(status,'') <> 'rejected'",
                (business_id,)).fetchone()["n"]
        if still == 0:
            from . import scheduler as _sch
            for s in _sch.list_schedules(business_id):
                if s.get("job_type") == "notebooklm_render":
                    _sch.delete_schedule(business_id, s["id"])
    except Exception:  # noqa: BLE001
        pass
    return {"ok": True, "downloaded": done, "failed": failed, "checked": len(targets)}


def poll_pending_agent_renders(business_id: int) -> dict:
    """Completion sweep for async v3 Video Agent renders: for each draft flagged `rendering`, check the
    session and — when ready — download + store the MP4/SRT as a video visual_asset and mark the draft
    `rendered`. Cheap no-op when nothing is pending. Removes its own hourly schedule once the queue is
    empty so it doesn't poll forever. Runs on the worker; each check is a couple HTTP calls, not a
    long block."""
    _ensure_table()
    try:
        from . import heygen_video as _hg
    except ImportError:  # pragma: no cover
        import heygen_video as _hg  # type: ignore
    with db() as conn:
        rows = conn.execute(
            "SELECT id, quality_notes FROM rich_media_drafts WHERE business_id=%s "
            "AND quality_notes->'rendered_video'->>'status' = 'rendering' "
            "AND quality_notes->'rendered_video'->>'provider' = 'heygen_agent'", (business_id,)).fetchall()
    maxa = int(os.getenv("AGENT_POLL_MAX_ATTEMPTS", "60"))
    done = still = failed = 0
    for r in rows:
        qn = dict(r.get("quality_notes") or {})
        rv = dict(qn.get("rendered_video") or {})
        sid = rv.get("session_id")
        if not sid:
            continue
        res = _hg.fetch_agent_video(business_id, sid, video_id=rv.get("video_id"),
                                    prompt=rv.get("prompt") or "", work_order_id=rv.get("work_order_id"),
                                    draft_id=r["id"])
        if res.get("ok"):
            rv.update({"status": "rendered", "visual_id": res.get("visual_id"),
                       "video_url": res.get("video_url"), "duration": res.get("duration")})
            done += 1
        elif res.get("failed"):
            rv.update({"status": "failed", "error": (res.get("error") or "")[:300]})
            failed += 1
        else:   # pending or a transient fetch error -> retry next sweep, up to maxa
            rv["attempts"] = (rv.get("attempts") or 0) + 1
            if rv["attempts"] > maxa:
                rv["status"] = "timed_out"
                failed += 1
            else:
                still += 1
        qn["rendered_video"] = rv
        with db() as conn:
            conn.execute("UPDATE rich_media_drafts SET quality_notes=%s, updated_at=now() "
                         "WHERE id=%s AND business_id=%s", (json.dumps(qn), r["id"], business_id))
            conn.commit()
    # Nothing left rendering -> stop the hourly sweep (self-clean).
    if still == 0:
        try:
            from . import scheduler as _sch
            for s in _sch.list_schedules(business_id):
                if s.get("job_type") == "poll_video_renders":
                    _sch.delete_schedule(business_id, s["id"])
        except Exception:  # noqa: BLE001
            pass
    return {"rendered": done, "still_rendering": still, "failed": failed, "checked": len(rows)}


def list_drafts(business_id: int) -> None:
    _ensure_table()
    with db() as conn:
        rows = conn.execute(
            """SELECT id, asset_type, title, audio_url, compliance_pass, status
               FROM rich_media_drafts
               WHERE business_id=%s ORDER BY id DESC""",
            (business_id,),
        ).fetchall()
    for r in rows:
        audio = " [audio]" if r["audio_url"] else ""
        print(f"  [{r['id']}] {r['status']:<14} compliance={r['compliance_pass']}"
              f"{audio} {r['asset_type']}: {r['title']}")
    if not rows:
        print("  (no rich-media drafts yet)")


