"""
Reputation Crowding-Out Engine -- Rich Media Generator
======================================================
Produces content types that require multi-source synthesis, not just single-topic
drafting:

  podcast            Audio Overview -- two-host AI podcast from audit + gap data.
  explainer_video    Explainer video script synthesised from all sources.
  slide_deck         Executive slide-deck brief (10-12 slides) from a study guide.
  infographic        Infographic content brief from a synthesised FAQ.
  research_brief     Deep research brief (briefing doc) for PR/content teams.
  deep_article       Long-form thought-leadership article (1 500-2 500 words).
  blog_series        Three related blog post outlines from topic synthesis.
  newsletter         Client newsletter brief combining audit insights.
  report_audio       Audio version of the monthly report.

Gemini and VEO content (answer-engine scoring, video production briefs) is
generated by the existing ai_state_audit.py and production_brief.py modules.
This module adds the NotebookLM API layer ON TOP of those, so the two content
paths complement rather than duplicate each other.

Design invariants (identical to the rest of the engine):
  - Fail-closed: any API/generation error stores None or skips the asset.
  - Budget-gated: over_budget() is checked before every external call.
  - Human gate: all output lands in ``rich_media_drafts`` as ``pending_review``.
    Nothing is auto-published.
  - Untrusted fencing: root-cause / competitor text is fenced as DATA before
    being added to any NotebookLM corpus.
  - Ephemeral corpora: every corpus is created, used, and deleted in one call.
  - Compliance gate: text output is screened through the same deterministic
    financial-marketing compliance patterns as Module 6.

CLI:
    python -m rep_engine.rich_media_generator --business-id 1
    python -m rep_engine.rich_media_generator --business-id 1 --types podcast,slide_deck
"""

