log = logging.getLogger("rich_media_generator")

# ---------------------------------------------------------------------------
# Supported rich-media types and their generation pathway
# ---------------------------------------------------------------------------
# Each entry: (asset_type, generation_method, description)
#   generation_method:
#     "notebooklm_audio"  -- NotebookLM Audio Overview (returns audio URL + transcript)
#     "notebooklm_note"   -- NotebookLM note synthesis (returns markdown text)
#     "llm_structured"    -- in-house LLM with structured multi-source prompt
RICH_TYPES: dict[str, tuple[str, str]] = {
    "podcast":          ("notebooklm_audio", "Two-host AI podcast from audit data"),
    "report_audio":     ("notebooklm_audio", "Audio version of the monthly report"),
    "explainer_video":  ("notebooklm_note",  "Explainer video script from all sources"),
    "slide_deck":       ("notebooklm_note",  "Executive slide-deck brief (10-12 slides)"),
    "infographic":      ("notebooklm_note",  "Infographic content brief from FAQ synthesis"),
    "research_brief":   ("notebooklm_note",  "Deep research brief for PR / content teams"),
    "deep_article":     ("llm_structured",   "Long-form thought-leadership article"),
    "blog_series":      ("llm_structured",   "Three related blog post outlines"),
    "newsletter":       ("llm_structured",   "Client newsletter brief with audit insights"),
}

# Default set generated per cycle (audio generation is the slowest/costliest).
DEFAULT_TYPES = list(RICH_TYPES.keys())

# Hard financial-marketing prohibitions — mirrors Module 6's compliance gate.
_COMPLIANCE_PATTERNS = [
    (re.compile(
        r"\bguarantee[ds]?\b[^.\n]{0,40}\b(returns?|profits?|income|results?|gains?|growth)\b",
        re.I), "implies guaranteed returns/results"),
    (re.compile(r"\b(risk[-\s]?free|no[-\s]?risk|zero[-\s]?risk)\b", re.I),
     "claims risk-free"),
    (re.compile(r"\b(?:#\s?1|number[-\s]one|the\sbest|best[-\s]in[-\s]class)\b", re.I),
     "unverifiable superlative (#1 / best)"),
    (re.compile(
        r"\b\d{1,3}\s?%[^.\n]{0,30}\b(guaranteed|returns?|profits?|gains?)\b", re.I),
     "specific performance promise"),
]


