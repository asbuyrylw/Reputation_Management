def _ensure_table() -> None:
    with db() as conn:
        conn.execute("""
            CREATE TABLE IF NOT EXISTS rich_media_drafts (
                id            BIGSERIAL PRIMARY KEY,
                business_id   BIGINT,
                asset_type    TEXT,
                title         TEXT,
                body          TEXT,
                audio_url     TEXT,
                transcript    TEXT,
                duration_secs INT,
                sources_used  JSONB DEFAULT '[]'::jsonb,
                compliance_pass   BOOLEAN,
                compliance_flags  JSONB DEFAULT '[]'::jsonb,
                status            TEXT DEFAULT 'pending_review',
                reviewer          TEXT,
                reviewed_at       TIMESTAMPTZ,
                created_at        TIMESTAMPTZ DEFAULT now(),
                updated_at        TIMESTAMPTZ DEFAULT now()
            )
        """)
        # Provenance: which engine actually produced this asset (notebooklm | llm). Honest disclosure
        # so a draft is never misrepresented as NotebookLM output when it was the in-house LLM.
        conn.execute("ALTER TABLE rich_media_drafts ADD COLUMN IF NOT EXISTS generator TEXT")
        # Deep link to open the piece in an external tool (e.g. the NotebookLM Studio page where the
        # owner listens to / downloads the generated podcast, since Google exposes no audio-download API).
        conn.execute("ALTER TABLE rich_media_drafts ADD COLUMN IF NOT EXISTS notebook_url TEXT")
        # Video/rich-media grade: overall citability score + the full per-dimension scorecard
        # (AEO/GEO, information, production, video SEO, length), same shape idea as content_drafts.
        conn.execute("ALTER TABLE rich_media_drafts ADD COLUMN IF NOT EXISTS geo_score NUMERIC")
        conn.execute("ALTER TABLE rich_media_drafts ADD COLUMN IF NOT EXISTS quality_notes JSONB")
        # Link the rich-media draft to the work order that produced it, so a rendered video/asset is
        # attributed to its WO (and, through it, its campaign/gap) for the impact loop -- and so the
        # render paths can pass a real work_order_id to visual_content instead of None.
        conn.execute("ALTER TABLE rich_media_drafts ADD COLUMN IF NOT EXISTS work_order_id BIGINT")
        # Measurement linkage: the content_impact batch this piece belongs to + the canonical gap_key it
        # closes, so rich media (podcast/video/slide/research_brief/deep_content) earns gap-completion
        # credit + impact measurement like text drafts do (it was written with only work_order_id, so it
        # never joined content_impact / gap_completion and its GEO grade never fed the strategist mix).
        conn.execute("ALTER TABLE rich_media_drafts ADD COLUMN IF NOT EXISTS batch_id BIGINT")
        conn.execute("ALTER TABLE rich_media_drafts ADD COLUMN IF NOT EXISTS gap_key TEXT")
        conn.execute(
            "CREATE INDEX IF NOT EXISTS idx_rmedia_biz "
            "ON rich_media_drafts(business_id, status)"
        )
        conn.execute("CREATE INDEX IF NOT EXISTS idx_rmedia_batch ON rich_media_drafts(batch_id)")
        conn.commit()


