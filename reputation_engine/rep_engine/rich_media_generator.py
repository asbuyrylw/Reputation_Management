def _generate_note_asset(
    asset_type: str, biz: dict, sources: list[dict], business_id: int
) -> Optional[str]:
    """Generate a note-type asset (explainer script / slide-deck brief / infographic brief /
    research brief). There is no working NotebookLM NOTE provider — Enterprise exposes audio
    overviews, and the old public note endpoint is dead — so these are produced by the in-house LLM.
    Returns markdown."""
    if _tools.over_budget(business_id):
        raise _tools.BudgetExceededError(f"business {business_id} is over monthly budget")
    # Return the raw LLM markdown directly. (The old _format_note() wrapper was dead code -- it
    # prepended editor-facing 'Instructions for production/designer:' preambles, which violate the
    # publish-ready policy, so it was removed rather than reactivated.)
    return _fallback_llm(asset_type, biz, sources, business_id)


def _fallback_llm(
    asset_type: str, biz: dict, sources: list[dict], business_id: int
) -> Optional[str]:
    """In-house LLM fallback when NotebookLM key is absent or generation fails."""
    template = _LLM_PROMPTS.get(asset_type)
    if not template:
        # For note-type assets, build a generic structured prompt.
        template = (
            "Using the context below, generate a {asset_type} for {{name}}. "
            "Format clearly in markdown. No fabricated facts, no performance promises."
        ).format(asset_type=asset_type.replace("_", " "))
    # Load the StrategyProfile ONCE: regulated_financial gates the finance-compliance clause + the
    # license ban. A generic tenant gets neither (only the universal deceptive-claims rule). Fail-safe.
    try:
        _profile = _bp.for_business(business_id)
    except Exception:  # noqa: BLE001
        _profile = None
    _fin_clause = (" Apply financial-marketing compliance: no guaranteed returns, no 'risk-free', no "
                   "performance promises.") if (_profile and _profile.get("regulated_financial")) else ""
    system = (
        "You are an expert reputation marketing strategist. Write structured, accurate "
        "content for reputation management. Never fabricate statistics, credentials, or "
        "performance data; the business's own website/profile (in the context) is authoritative "
        "for its name, address, services, and website URL -- use those real facts and WRITE AROUND "
        "anything unknown (omit it or use general wording / point to the website) instead of leaving "
        "[INSERT] placeholders. Do NOT use unverifiable '#1' or 'best' claims as stated fact. Output "
        "ONLY the asset content in markdown."
        + _fin_clause
        # Business-agnostic license/sensitive-ID ban: '' for a generic tenant, today's finance policy
        # for a regulated-finance tenant. Reuses the profile loaded above (no extra query).
        + _bp.license_policy_for(_profile)
        + _tools.NO_NEGATIVE_DISAMBIGUATION_POLICY
    )
    prompt_text = template.format(name=biz.get("name", "the business"))
    # Add source context. The client's own material (Business Profile, Requested Focus, BRAND RULES,
    # Client Source Material) leads the sources list, so keep the first 6 and allow a generous
    # per-source budget — the old 5x3000-char cap dropped ~90% of a large uploaded corpus.
    context = "\n\n---\n\n".join(
        f"## {s['title']}\n{s['text'][:6_000]}" for s in sources[:6]
    )
    user = f"{prompt_text}\n\n# Context\n\n{context}"
    try:
        if _tools.over_budget(business_id):
            raise _tools.BudgetExceededError(
                f"business {business_id} is over monthly budget")
        return _tools.llm_text(
            system, user,
            business_id=business_id,
            tier="mid",
            max_tokens=_MAX_TOKENS.get(asset_type, _DEFAULT_MAX_TOKENS),
            operation=f"rich_media_{asset_type}",
        )
    except _tools.BudgetExceededError:
        raise
    except Exception as e:
        log.warning("rich_media: LLM fallback for %s failed: %s", asset_type, e)
        return None


def _generate_llm_asset(
    asset_type: str, biz: dict, sources: list[dict], business_id: int
) -> Optional[str]:
    """Generate an LLM-structured asset using the in-house LLM path."""
    return _fallback_llm(asset_type, biz, sources, business_id)


