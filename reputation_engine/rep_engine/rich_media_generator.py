def main() -> None:
    ap = argparse.ArgumentParser(
        description="Rich Media Generator — podcast, slides, infographics, articles via NotebookLM"
    )
    sub = ap.add_subparsers(dest="cmd", required=True)

    g = sub.add_parser("generate")
    g.add_argument("--business-id", type=int, required=True)
    g.add_argument(
        "--types",
        help=(
            "Comma-separated list of asset types to generate "
            f"(default: all). Choices: {', '.join(RICH_TYPES)}"
        ),
    )

    l = sub.add_parser("list")
    l.add_argument("--business-id", type=int, required=True)

    args = ap.parse_args()
    if args.cmd == "generate":
        types = [t.strip() for t in args.types.split(",")] if args.types else None
        ids = generate(args.business_id, types)
        print(json.dumps({"created": ids}))
    elif args.cmd == "list":
        list_drafts(args.business_id)


if __name__ == "__main__":
    main()
