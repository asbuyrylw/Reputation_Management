def _persist(
    business_id: int,
    asset_type: str,
    title: str,
    *,
    body: Optional[str] = None,
    audio_url: Optional[str] = None,
    transcript: Optional[str] = None,
    duration_secs: Optional[int] = None,
    sources_used: list | None = None,
    compliance_pass: Optional[bool] = None,
    compliance_flags: list | None = None,
    generator: str = "llm",
    notebook_url: Optional[str] = None,
    business_name: str = "",
    geo: str = "",
    work_order_id: Optional[int] = None,
    batch_id: Optional[int] = None,
    gap_key: Optional[str] = None,
) -> int:
    # Publish-ready: rich-media scripts/briefs go through the SAME placeholder strip + license-number
    # scrub as text drafts, so a video/slide/infographic never ships with an [INSERT: ...] or a
    # specific license number. Best-effort (lazy import avoids a load-time cycle).
    if body:
        try:
            from . import content_generator as _cg
            from . import content_quality as _cqs
            # License-number scrub is gated on the tenant's profile: a generic tenant keeps license
            # numbers; a regulated-finance tenant has them scrubbed. Fail-safe: profile None -> scrub runs.
            _profile = _bp.for_business(business_id)
            body = _cg._scrub_license_phrasing(_cg._strip_placeholders(body), _profile)
            body = _cqs.scrub_slop(body)   # de-generic: strip formulaic AI-slop lead-ins
            # Crowd-out enforcement, SAME as text drafts: keep scam/pyramid/MLM out of the headings +
            # lead + title. deep_article/research_brief previously bypassed this entirely, so a
            # long-form piece could bind the brand to the contested token in its most-cited locations.
            _contested = ""
            try:
                with db() as _c2:
                    _r = _c2.execute("SELECT contested_terms FROM businesses WHERE id=%s",
                                     (business_id,)).fetchone()
                _contested = (_r.get("contested_terms") or "") if _r else ""
            except Exception:  # noqa: BLE001 -- column may be absent; neutralize is a no-op on clean text
                _contested = ""
            body = _cg.neutralize_contested(body, _contested)
            title = _cg._neutralize_contested_title(title, _contested)
            # Title uniqueness (same as text drafts): a deep_article/research_brief title that collides
            # with an existing one gets the next ' (v2)'/'(v3)' so the media list never shows dupes.
            title = _cg._dedupe_title(business_id, title, table="rich_media_drafts")
            # E-E-A-T byline on the one true published-ARTICLE rich type (deep_article), authored the
            # same way as content drafts: a random named author from the roster. Decks/briefs/scripts
            # are not articles, so they get no prose byline. No-op if business_name is unknown.
            if asset_type == "deep_article":
                _p = _profile if isinstance(_profile, dict) else {}
                body = _cg._ensure_byline(
                    body, business_name or "",
                    reviewer=_p.get("byline_reviewer") or "editorial team",
                    author=_p.get("byline_author") or "",
                    authors=_p.get("byline_authors"))
        except Exception as e:  # noqa: BLE001 -- cleanup must never block persistence
            log.debug("rich_media: body cleanup skipped: %s", e)
    # Grade video scripts (AEO/GEO citability first, then info/production/SEO/length) so a video is
    # scored like text. Runs on the CLEANED body. Best-effort; non-video types get no grade.
    quality_notes = None
    geo_grade = None
    if body and asset_type in ("explainer_video", "video_script"):
        try:
            from . import content_quality as _cq
            _q = f"{business_name} {geo}".strip()   # neutral scoring query (was hardcoded 'financial services')
            vg = _cq.video_score(body, target_query=_q, business_name=business_name, geo=geo,
                                 asset_type=asset_type)
            quality_notes, geo_grade = vg, vg.get("score")
            duration_secs = duration_secs or (vg.get("runtime_secs") or None)
            # Citability layer (no render needed): AI cites a video via its CAPTIONS/transcript, so
            # attach an SRT caption sidecar + a VideoObject JSON-LD (transcript-carrying) to the draft.
            # contentUrl fills in later once a real video is rendered/published.
            try:
                from datetime import datetime as _dt, timezone as _tz
                _srt = _cq.to_srt(body)
                _spoken = _cq._spoken_only(body).strip()
                _schema = _cq.video_object_schema(
                    title=title, description=(_spoken[:300] or title), transcript=(transcript or _spoken),
                    duration_secs=int(duration_secs or 0), business_name=business_name, geo=geo,
                    upload_date=f"{_dt.now(_tz.utc):%Y-%m-%d}")
                quality_notes = dict(vg); quality_notes["captions_srt"] = _srt
                quality_notes["video_schema"] = _schema
                if not transcript:
                    transcript = _spoken
            except Exception as e2:  # noqa: BLE001
                log.debug("rich_media: caption/schema build skipped: %s", e2)
        except Exception as e:  # noqa: BLE001 -- grading must never block persistence
            log.debug("rich_media: video grading skipped: %s", e)
    elif body and (asset_type not in ("podcast", "report_audio") or len((body or "").split()) >= 120):
        # ALSO score substantial audio TRANSCRIPTS (an LLM two-host podcast script, 600-900 words) with
        # the same GEO/citability grade -- the transcript IS the citable content. The short NotebookLM
        # "open in Studio to listen" link message (~50 words) is naturally excluded by the word gate.
        # TEXT-like rich media (deep_article, research_brief, slide_deck, infographic) was shipping
        # UNSCORED -- geo_score + quality_notes both null, so no GEO/AEO/citation grade on half the
        # content library. Grade it with the same GEO scorer as an article. Best-effort.
        try:
            from . import content_quality as _cq
            _q = f"{business_name} {geo}".strip()
            _geo = _cq.geo_score(body, target_query=_q, content_type=asset_type, asset_type=asset_type,
                                 business_name=business_name, geo=geo)
            quality_notes = {"geo": _geo}
            geo_grade = _geo.get("score")
        except Exception as e:  # noqa: BLE001 -- grading must never block persistence
            log.debug("rich_media: text grading skipped: %s", e)
    # Truncation guard (silent-failure fix): an LLM hitting its token cap leaves the body ending
    # mid-sentence while the job still reports 'complete' (the research brief + slide deck both did).
    # Detect it, flag it in quality_notes, and route the draft to needs_fix so a truncated piece is
    # never presented as ready-to-review.
    _status = "pending_review"
    if body and len(body.split()) >= 120:
        _tail = body.rstrip()
        if _tail and _tail[-1] not in ".!?\"”')]:*_`>":
            quality_notes = dict(quality_notes or {})
            quality_notes["truncated"] = {"ends_with": _tail[-80:],
                                          "reason": "body ends mid-sentence (likely token-cap truncation)"}
            _status = "needs_fix"
            log.warning("rich_media: %s draft appears TRUNCATED (ends mid-sentence) -> needs_fix", asset_type)
    with db() as conn:
        row = conn.execute(
            """INSERT INTO rich_media_drafts
               (business_id, asset_type, title, body, audio_url, transcript,
                duration_secs, sources_used, compliance_pass, compliance_flags, generator,
                notebook_url, geo_score, quality_notes, status, work_order_id, batch_id, gap_key)
               VALUES (%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s) RETURNING id""",
            (business_id, asset_type, title,
             body, audio_url, transcript, duration_secs,
             json.dumps(sources_used or []),
             compliance_pass, json.dumps(compliance_flags or []), generator, notebook_url,
             geo_grade, json.dumps(quality_notes) if quality_notes else None, _status, work_order_id,
             batch_id, gap_key),
        ).fetchone()
        conn.commit()
    log.info("rich_media: saved draft %d (%s, generator=%s, compliance=%s, grade=%s)", row["id"],
             asset_type, generator, compliance_pass, geo_grade)
    return row["id"]


